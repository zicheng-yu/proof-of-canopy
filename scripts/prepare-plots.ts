// Builds canonical plot geometries and data/plots/manifest.json from data/plots/plots.config.json.
// A plot comes either from `source` (a GeoJSON file exported from EO Browser, relative to data/plots)
// or, as a placeholder, from a `center` point expanded to a square of `areaHectares`.
import { readFileSync, writeFileSync } from 'node:fs';
import { keccak256, toBytes } from 'viem';
import {
  areaHectares, canonicalGeoJson, canonicalRing, centroid, h3Cells, ringFromGeoJson, squareAround,
  type LonLat,
} from './lib/geo.ts';
import { fromRoot, readJson, writeJson } from './lib/paths.ts';

interface PlotConfig {
  id: string;
  role: 'healthy' | 'degraded' | 'burned';
  name: string;
  region: string;
  center?: LonLat;
  source?: string;
  placeholder?: boolean;
  note?: string;
}

interface Config {
  areaHectares: number;
  h3Resolution: number;
  plots: PlotConfig[];
}

const config = readJson<Config>(fromRoot('data/plots/plots.config.json'));

const plots = config.plots.map((plot) => {
  let raw: LonLat[];
  if (plot.source) raw = ringFromGeoJson(readFileSync(fromRoot('data/plots', plot.source), 'utf8'));
  else if (plot.center) raw = squareAround(plot.center, config.areaHectares);
  else throw new Error(`${plot.id}: needs "source" or "center"`);

  const ring = canonicalRing(raw);
  const text = canonicalGeoJson(ring);
  const file = `${plot.id}.geojson`;
  writeFileSync(fromRoot('data/plots', file), text);

  const cells = h3Cells(ring, config.h3Resolution);
  if (cells.length === 0) throw new Error(`${plot.id}: polygon covers no H3 cell centres`);

  return {
    id: plot.id,
    role: plot.role,
    name: plot.name,
    region: plot.region,
    placeholder: plot.placeholder ?? false,
    file,
    plotHash: keccak256(toBytes(text)),
    areaHectares: Math.round(areaHectares(ring)),
    centroid: centroid(ring),
    cellCount: cells.length,
    cells: cells.map(String),
  };
});

writeJson(fromRoot('data/plots/manifest.json'), {
  note: 'Generated by scripts/prepare-plots.ts. plotHash = keccak256(bytes of <file>). cells are H3 indexes as uint64.',
  h3Resolution: config.h3Resolution,
  plots,
});

for (const p of plots) {
  console.log(`${p.id.padEnd(22)} ${p.role.padEnd(9)} ${String(p.areaHectares).padStart(4)} ha  ${String(p.cellCount).padStart(3)} cells  ${p.plotHash}`);
}
