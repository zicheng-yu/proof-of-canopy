// Writes web/src/abi.ts from Foundry's build output, so the web app gets typed ABIs without Foundry.
// Run after changing a contract: npm run build && npm run abis
import { readFileSync, writeFileSync } from 'node:fs';
import { fromRoot } from './lib/paths.ts';

const NAMES = ['ProjectRegistry', 'SurvivalOracle', 'MilestoneEscrow'] as const;

let out = '// Generated by scripts/export-abis.ts from contracts/out. Do not edit by hand.\n';
for (const name of NAMES) {
  const { abi } = JSON.parse(readFileSync(fromRoot('contracts/out', `${name}.sol`, `${name}.json`), 'utf8'));
  const id = `${name[0].toLowerCase()}${name.slice(1)}Abi`;
  out += `\nexport const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(fromRoot('web/src/abi.ts'), out);
console.log('wrote web/src/abi.ts');
